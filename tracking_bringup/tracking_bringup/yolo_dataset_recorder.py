from __future__ import annotations

import math
from pathlib import Path
from typing import Dict, Optional, Tuple

import cv2
import numpy as np
import rclpy
from cv_bridge import CvBridge
from geometry_msgs.msg import PoseStamped
from rclpy.node import Node
from sensor_msgs.msg import CameraInfo, Image


class LatestPose:
    def __init__(self):
        self.x: Optional[float] = None
        self.y: Optional[float] = None
        self.stamp_sec: Optional[float] = None

    def update(self, msg: PoseStamped):
        self.x = float(msg.pose.position.x)
        self.y = float(msg.pose.position.y)
        self.stamp_sec = float(msg.header.stamp.sec) + float(msg.header.stamp.nanosec) * 1e-9

    def valid(self, image_stamp_sec: float, max_age_sec: float) -> bool:
        if self.x is None or self.y is None or self.stamp_sec is None:
            return False
        return abs(image_stamp_sec - self.stamp_sec) <= max_age_sec


class YoloDatasetRecorder(Node):
    def __init__(self):
        super().__init__("yolo_dataset_recorder")

        self.declare_parameter(
            "image_topic",
            "/world/default/model/overhead_camera/link/camera_link/sensor/overhead_camera_sensor/image",
        )
        self.declare_parameter(
            "camera_info_topic",
            "/world/default/model/overhead_camera/link/camera_link/sensor/overhead_camera_sensor/camera_info",
        )
        self.declare_parameter("gt_topic_prefix", "/ground_truth_pose_")
        self.declare_parameter("robot_ids", [0, 1, 2, 3, 4, 5])
        self.declare_parameter("output_dir", str(Path.home() / "wspace" / "yolo_dataset"))
        self.declare_parameter("save_every_n", 5)
        self.declare_parameter("val_every_n", 10)
        self.declare_parameter("max_gt_age_sec", 0.20)

        self.declare_parameter("camera_height_m", 10.0)
        self.declare_parameter("ground_z_m", 0.0)
        self.declare_parameter("x_offset", 0.0)
        self.declare_parameter("y_offset", 0.0)
        self.declare_parameter("robot_box_size_m", 0.62)
        self.declare_parameter("class_id", 0)
        self.declare_parameter("class_name", "robot")

        self.image_topic = str(self.get_parameter("image_topic").value)
        self.camera_info_topic = str(self.get_parameter("camera_info_topic").value)
        self.gt_topic_prefix = str(self.get_parameter("gt_topic_prefix").value)
        self.robot_ids = [int(v) for v in self.get_parameter("robot_ids").value]
        self.output_dir = Path(str(self.get_parameter("output_dir").value)).expanduser()
        self.save_every_n = int(self.get_parameter("save_every_n").value)
        self.val_every_n = int(self.get_parameter("val_every_n").value)
        self.max_gt_age_sec = float(self.get_parameter("max_gt_age_sec").value)
        self.camera_height_m = float(self.get_parameter("camera_height_m").value)
        self.ground_z_m = float(self.get_parameter("ground_z_m").value)
        self.x_offset = float(self.get_parameter("x_offset").value)
        self.y_offset = float(self.get_parameter("y_offset").value)
        self.robot_box_size_m = float(self.get_parameter("robot_box_size_m").value)
        self.class_id = int(self.get_parameter("class_id").value)
        self.class_name = str(self.get_parameter("class_name").value)

        self.bridge = CvBridge()
        self.camera_matrix: Optional[np.ndarray] = None
        self.frame_count = 0
        self.saved_count = 0

        self.poses: Dict[int, LatestPose] = {rid: LatestPose() for rid in self.robot_ids}

        for split in ("train", "val"):
            (self.output_dir / split / "images").mkdir(parents=True, exist_ok=True)
            (self.output_dir / split / "labels").mkdir(parents=True, exist_ok=True)
        self.write_data_yaml()

        self.image_sub = self.create_subscription(Image, self.image_topic, self.image_callback, 10)
        self.camera_info_sub = self.create_subscription(CameraInfo, self.camera_info_topic, self.camera_info_callback, 10)
        for rid in self.robot_ids:
            topic = f"{self.gt_topic_prefix}{rid}"
            self.create_subscription(PoseStamped, topic, self._make_gt_cb(rid), 10)
            self.get_logger().info(f"GT for labels: robot_id={rid} <- {topic}")

        self.get_logger().info(f"YOLO dataset output: {self.output_dir}")

    def write_data_yaml(self):
        data_yaml = self.output_dir / "data.yaml"
        data_yaml.write_text(
            "# Generated by tracking_bringup.yolo_dataset_recorder\n"
            f"path: {self.output_dir}\n"
            "train: train/images\n"
            "val: val/images\n"
            "names:\n"
            f"  {self.class_id}: {self.class_name}\n",
            encoding="utf-8",
        )

    def _make_gt_cb(self, robot_id: int):
        def cb(msg: PoseStamped):
            self.poses[robot_id].update(msg)
        return cb

    def camera_info_callback(self, msg: CameraInfo):
        self.camera_matrix = np.array(msg.k, dtype=np.float64).reshape(3, 3)

    def world_to_pixel(self, x: float, y: float) -> Optional[Tuple[float, float]]:
        if self.camera_matrix is None:
            return None
        fx = float(self.camera_matrix[0, 0])
        fy = float(self.camera_matrix[1, 1])
        cx = float(self.camera_matrix[0, 2])
        cy = float(self.camera_matrix[1, 2])
        depth = self.camera_height_m - self.ground_z_m
        if depth <= 0.0 or fx == 0.0 or fy == 0.0:
            return None

        cam_y = self.x_offset - x
        cam_x = self.y_offset - y
        u = cx + fx * cam_x / depth
        v = cy + fy * cam_y / depth
        return u, v

    def image_callback(self, msg: Image):
        self.frame_count += 1
        if self.camera_matrix is None:
            return
        if self.frame_count % max(1, self.save_every_n) != 0:
            return

        image_stamp_sec = float(msg.header.stamp.sec) + float(msg.header.stamp.nanosec) * 1e-9
        frame = self.bridge.imgmsg_to_cv2(msg, desired_encoding="bgr8")
        h_img, w_img = frame.shape[:2]

        labels = []
        for rid, pose in self.poses.items():
            if not pose.valid(image_stamp_sec, self.max_gt_age_sec):
                continue
            uv = self.world_to_pixel(float(pose.x), float(pose.y))
            if uv is None:
                continue
            u, v = uv
            box_w_px = self.robot_box_size_m * float(self.camera_matrix[0, 0]) / (self.camera_height_m - self.ground_z_m)
            box_h_px = self.robot_box_size_m * float(self.camera_matrix[1, 1]) / (self.camera_height_m - self.ground_z_m)

            x_center = u / w_img
            y_center = v / h_img
            bw = box_w_px / w_img
            bh = box_h_px / h_img

            if x_center < -0.1 or x_center > 1.1 or y_center < -0.1 or y_center > 1.1:
                continue

            x_center = min(1.0, max(0.0, x_center))
            y_center = min(1.0, max(0.0, y_center))
            bw = min(1.0, max(0.001, bw))
            bh = min(1.0, max(0.001, bh))
            labels.append(f"{self.class_id} {x_center:.8f} {y_center:.8f} {bw:.8f} {bh:.8f}")

        if not labels:
            return

        split = "val" if self.saved_count > 0 and self.saved_count % max(1, self.val_every_n) == 0 else "train"
        name = f"gazebo_{self.saved_count:06d}"
        image_path = self.output_dir / split / "images" / f"{name}.jpg"
        label_path = self.output_dir / split / "labels" / f"{name}.txt"
        cv2.imwrite(str(image_path), frame)
        label_path.write_text("\n".join(labels) + "\n", encoding="utf-8")

        self.saved_count += 1
        if self.saved_count % 50 == 1:
            self.get_logger().info(f"Saved {self.saved_count} YOLO samples, last={image_path}, labels={len(labels)}")


def main(args=None):
    rclpy.init(args=args)
    node = YoloDatasetRecorder()
    try:
        rclpy.spin(node)
    except KeyboardInterrupt:
        pass
    finally:
        node.destroy_node()
        if rclpy.ok():
            rclpy.shutdown()


if __name__ == "__main__":
    main()
